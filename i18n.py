from datetime import datetime as _dt, timedelta as _td, timezone as _tz

_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
_ASCII_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")


def tf(lang, key, **kw):
    """t() + str.format; never raises (a bad template just returns the raw text)."""
    s = t(lang, key)
    try:
        return s.format(**kw)
    except Exception:
        return s


def num(lang, value):
    """Display a number/identifier-free value; Persian digits in fa."""
    s = str(value)
    return s.translate(_FA_DIGITS) if lang == "fa" else s


def fmt_amount(lang, value):
    try:
        f = float(value)
    except (TypeError, ValueError):
        return str(value)
    s = f"{int(f):,}" if f == int(f) else f"{f:,.2f}"
    if lang == "fa":
        s = s.translate(_FA_DIGITS).replace(",", "٬")
    return s


def to_ascii_digits(s):
    """Persian/Arabic digits -> 0-9 (for phone numbers and postal codes)."""
    return str(s or "").translate(_ASCII_DIGITS)


def gregorian_to_jalali(gy, gm, gd):
    g_d_m = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
    if gy > 1600:
        jy, gy = 979, gy - 1600
    else:
        jy, gy = 0, gy - 621
    gy2 = gy + 1 if gm > 2 else gy
    days = (365 * gy) + ((gy2 + 3) // 4) - ((gy2 + 99) // 100) + ((gy2 + 399) // 400) - 80 + gd + g_d_m[gm - 1]
    jy += 33 * (days // 12053)
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm, jd = 1 + days // 31, 1 + days % 31
    else:
        jm, jd = 7 + (days - 186) // 30, 1 + (days - 186) % 30
    return jy, jm, jd


def fmt_date(lang, value, with_time=True):
    """Persian users see the Jalali date (Iran time); English users see ISO (UTC)."""
    if not value:
        return "-"
    try:
        d = _dt.fromisoformat(str(value).replace("Z", "+00:00"))
        if d.tzinfo is None:
            d = d.replace(tzinfo=_tz.utc)
    except Exception:
        return str(value)[:16]
    if lang == "fa":
        d = d.astimezone(_tz(_td(hours=3, minutes=30)))
        jy, jm, jd = gregorian_to_jalali(d.year, d.month, d.day)
        s = f"{jy:04d}/{jm:02d}/{jd:02d}" + (f" {d.hour:02d}:{d.minute:02d}" if with_time else "")
        return s.translate(_FA_DIGITS)
    d = d.astimezone(_tz.utc)
    return d.strftime("%Y-%m-%d") + (d.strftime(" %H:%M UTC") if with_time else "")
